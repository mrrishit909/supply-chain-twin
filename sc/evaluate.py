"""Offline evaluation on the full synthetic network. Writes docs/evaluation.md.

    python -m sc.evaluate
"""
import datetime
import pathlib
import time

import numpy as np

from . import models, twin, world


def main():
    w = world.build(today=datetime.date(2026, 10, 1))
    tw = twin.from_world(w)
    _, eta = models.train_eta(w["history"])
    _, risk, _, _ = models.train_risk(w["history"])
    port = next(k for k, v in tw.ports.items() if v == "Shanghai")
    rows = []
    for sev, dur in [(0.5, 14), (0.7, 21), (0.9, 21), (0.7, 42)]:
        hits = twin.affected(tw, port, sev, dur)
        t0 = time.perf_counter()
        opt = twin.optimize(tw, port, hits)
        secs = time.perf_counter() - t0
        plans = {"nothing": {"expedite": [], "extra": {}, "cost": twin.plan_cost(tw, [], [])}, "naive": twin.naive_plan(tw, hits), "opt": opt}
        net = {}
        for name, p in plans.items():
            t = twin.totals(twin.simulate(tw, twin.expected_arrivals(tw, hits, p), p["extra"]))
            net[name] = (float(t["lost_margin"][0]) + sum(p["cost"].values()), float(t["lost_revenue"][0]))
        rows.append((sev, dur, len(hits), max((d for _, d in hits), default=0), net, secs, opt["solver"]))
    t0 = time.perf_counter()
    mc, _, _ = twin.monte_carlo(tw, port, 0.7, 21)
    mc_s = time.perf_counter() - t0
    m = lambda x: f"${x / 1e6:,.2f}M"      # noqa: E731
    lines = ["# Evaluation", "",
             f"Generated by `python -m sc.evaluate` on the full synthetic network: {len(w['suppliers'])} suppliers, {len(w['facilities'])} facilities, {len(w['parts']):,} parts,",
             f"{len(w['shipments']):,} shipments over two years ({len(tw.ships):,} open or planned). All data is synthetic: the numbers show that each component beats its",
             "baseline on this generated world, not how it would do on a real supply chain.", "",
             "## 1. Arrival-time forecast", "",
             f"Trained on {eta['n_train']:,} deliveries, tested on the most recent {models.TEST_DAYS} days ({eta['n_test']:,} deliveries) it never saw.", "",
             "| | Mean absolute error |", "|---|---|",
             f"| Gradient boosting, median (`{models.ETA_VERSION}`) | {eta['model']['mae_days']} days |",
             f"| Baseline: lane median | {eta['baseline']['mae_days']} days |", f"| Baseline: the promised date | {eta['baseline']['promised_date_mae_days']} days |", "",
             f"The 80% interval (10th to 90th percentile models) contained the actual arrival {eta['model']['interval_80_coverage']:.0%} of the time and is {eta['model']['interval_80_width_days']} days wide on average.", "",
             "## 2. Supplier delay probability", "",
             f"Late = more than {models.LATE_DAYS} days after the promised date ({risk['late_rate_test']:.1%} of test deliveries).", "",
             "| | AUC | Brier score |", "|---|---|---|",
             f"| Calibrated gradient boosting (`{models.RISK_VERSION}`) | {risk['model']['auc']} | {risk['model']['brier']} |",
             f"| Baseline: overall late rate | {risk['baseline']['auc']} | {risk['baseline']['brier']} |", "",
             "## 3. Recovery plans", "",
             "Shanghai capacity cut at four depths and lengths. Net cost = lost margin + plan cost, in the expected case, judged by the daily simulator.", "",
             "| Capacity lost | Days | Shipments delayed | Max delay | Do nothing | Fly the most delayed first | Optimized (MIP) | Solve time |", "|---|---|---|---|---|---|---|---|"]
    for sev, dur, n, mx, net, secs, solver in rows:
        lines.append(f"| {sev:.0%} | {dur} | {n:,} | {mx:.1f} d | {m(net['nothing'][0])} | {m(net['naive'][0])} | {m(net['opt'][0])} | {secs:.1f} s ({solver['status']}) |")
    lines += ["", f"The model for the 70% / 21-day case has {rows[1][6]['variables']:,} variables and {rows[1][6]['constraints']:,} constraints (HiGHS).",
              "The optimizer plans for the expected delay only. Under uncertainty its cheap plan keeps less slack than flying everything; the demo's last step shows that tail.", "",
              "## 4. Monte Carlo", "",
              f"1,000 futures for the 70% / 21-day cut take {mc_s:.1f} s. Lost revenue: 10th percentile {m(np.percentile(mc['lost_revenue'], 10))}, median {m(np.percentile(mc['lost_revenue'], 50))}, "
              f"90th percentile {m(np.percentile(mc['lost_revenue'], 90))}.",
              "With the same transit noise and no port cut, lost revenue is zero in every future: the network was generated with enough safety stock for ordinary variation."]
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
